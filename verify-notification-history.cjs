'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { load, save, retained } = require('./notification-history.cjs');
const root = fs.mkdtempSync(path.join(__dirname, '.verification', 'history-'));
const sample = index => ({ id: index.toString(16).padStart(16, '0'), title: '标题', body: '完整通知内容 📱', appName: '微信', at: new Date().toISOString(), status: 'shown', client: 'private-client', token: 'never-persist' });
assert.deepEqual(load(root), []);
save(root, [sample(1)]);
assert.equal(load(root)[0].body, sample(1).body);
assert.equal(load(root)[0].id, sample(1).id);
assert.equal(load(root)[0].client, undefined);
assert.equal(load(root)[0].token, undefined);
assert.equal(retained(Array.from({ length: 205 }, (_, index) => sample(index + 1))).length, 200);
assert.equal(retained([{ ...sample(2), at: new Date(Date.now() - 8 * 86400000).toISOString() }]).length, 0);
assert.equal(retained([{ ...sample(2), id: '../../file' }]).length, 0);
assert.equal(retained([{ ...sample(2), body: 'a'.repeat(8001) }]).length, 0);
fs.writeFileSync(path.join(root, '.notification-history.json'), '{invalid');
assert.deepEqual(load(root), []);
console.log('PASS: Unicode survives disk reload; 200 records/7 days; IDs and size checked; client/token excluded; corrupt history recovers');
